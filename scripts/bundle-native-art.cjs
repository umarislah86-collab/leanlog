const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),ts=require('typescript'),sharp=require('sharp');
const root=path.join(__dirname,'..');
function load(file,mocks={}){const module={exports:{}};vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root,file),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module,exports:module.exports,require:id=>mocks[id]});return module.exports;}
const themes=load('services/appTheme.ts');
const art=load('services/themeArtwork.ts',{'./appTheme':themes,'./themeMotifs':load('services/themeMotifs.ts',{'./appTheme':themes}),'./characterImageData':load('services/characterImageData.ts'),'./cutieImageData':load('services/cutieImageData.ts')});
(async()=>{
 const rows=[],references=[],seen=new Map();
 for(const id of ['grandline','saiyan','cutie'])for(const place of ['home','log','progress','coach','drawer','widget','account','cash','quick','upcoming']){
  const motif=art.themeArtwork(id,place),key=id+'/'+motif.name;
  let variable=seen.get(key);
  if(!variable){
   variable='image'+seen.size;seen.set(key,variable);
   const png=await sharp(Buffer.from(motif.svg)).resize(320,320).ensureAlpha().png({palette:true,colours:256,dither:0}).toBuffer();
   const {data}=await sharp(png).raw().toBuffer({resolveWithObject:true});
   if(!data.some((v,i)=>i%4===3&&v>0))throw Error('Empty artwork '+key);
   const faded=Buffer.from(data);for(let i=3;i<faded.length;i+=4)faded[i]=Math.round(faded[i]*.24);
   const widget=await sharp(faded,{raw:{width:320,height:320,channels:4}}).png().toBuffer();
   rows.push('const '+variable+' = { uri:"data:image/png;base64,'+png.toString('base64')+'", widget:"data:image/png;base64,'+widget.toString('base64')+'" } as const;');
  }
  references.push(JSON.stringify(id+'/'+place)+':'+variable);
 }
 fs.writeFileSync(path.join(root,'services/nativeArtwork.ts'),'// Generated by scripts/bundle-native-art.cjs. PNG pixels, no runtime SVG image decoding.\n'+rows.join('\n')+'\nconst images:Record<string,{uri:`data:image${string}`;widget:`data:image${string}`}>={'+references.join(',')+'};\nexport const nativeArtwork=(id:string,place:string)=>images[id+"/"+place];\n');
})();
