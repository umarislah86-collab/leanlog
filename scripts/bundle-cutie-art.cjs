// Bundle user-provided artwork offline, preserving the supplied images.
const fs=require('node:fs'),path=require('node:path'),sharp=require('sharp');
const root=path.join(__dirname,'..');
const names=['sunshine','pinkSky','yummy','cool','cheer','thumbsUp','wow'];
// A vector clip for the sticker's connected outer black canvas. Source image
// pixels remain unchanged, including black eyes/hair enclosed by white outlines.
async function stickerClip(buffer,width,height){
 const raw=await sharp(buffer).ensureAlpha().raw().toBuffer();
 const outside=new Uint8Array(width*height),queue=[];
 const dark=i=>raw[i*4+3]===0||Math.max(raw[i*4],raw[i*4+1],raw[i*4+2])<=48;
 const add=i=>{if(!outside[i]&&dark(i)){outside[i]=1;queue.push(i);}};
 for(let x=0;x<width;x++){add(x);add((height-1)*width+x);}
 for(let y=0;y<height;y++){add(y*width);add(y*width+width-1);}
 for(let head=0;head<queue.length;head++){
  const i=queue[head],x=i%width,y=Math.floor(i/width);
  if(x>0)add(i-1);if(x+1<width)add(i+1);if(y>0)add(i-width);if(y+1<height)add(i+width);
 }
 const parts=[];
 for(let y=0;y<height;y++)for(let x=0;x<width;){
  if(outside[y*width+x]){x++;continue;}
  const start=x;while(x<width&&!outside[y*width+x])x++;
  parts.push(`M${start} ${y}h${x-start}v1h-${x-start}Z`);
 }
 return parts.join('');
}
(async()=>{
 const rows=[];
 for(const name of names){
  const portrait=name==='sunshine'||name==='pinkSky';
  const resized=sharp(path.join(root,'assets/theme-cutie',`${name}.png`)).resize({width:portrait?512:320,withoutEnlargement:true});
  const buffer=await (portrait?resized.jpeg({quality:88}):resized.png()).toBuffer();
  const {width,height}=await sharp(buffer).metadata();
  const clip=portrait?'':await stickerClip(buffer,width,height);
  rows.push(`${name}: { width:${width}, height:${height}, clip:${JSON.stringify(clip)}, uri:'data:image/${portrait?'jpeg':'png'};base64,${buffer.toString('base64')}' }`);
 }
 fs.writeFileSync(path.join(root,'services/cutieImageData.ts'),'// Generated by scripts/bundle-cutie-art.cjs; user-supplied offline artwork.\nexport const cutieImages = {\n'+rows.join(',\n')+'\n} as const;\n');
})();
