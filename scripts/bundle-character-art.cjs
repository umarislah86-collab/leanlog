// Lossless character identity: package official source images, never redraw them.
const fs=require('node:fs'),path=require('node:path'),sharp=require('sharp');
const root=path.join(__dirname,'..');
const names=['luffy','zoro','sanji','chopper','goku','vegeta','piccolo','gohan'];
(async()=>{
 const rows=[];
 for(const name of names){
  const ext=names.indexOf(name)<4?'jpg':'png';
  const buffer=await sharp(path.join(root,'assets/theme-characters',`${name}.${ext}`)).resize({width:600,withoutEnlargement:true}).png().toBuffer();
  const {width,height}=await sharp(buffer).metadata();
  rows.push(`${name}: { width:${width}, height:${height}, uri:'data:image/png;base64,${buffer.toString('base64')}' }`);
 }
 fs.writeFileSync(path.join(root,'services/characterImageData.ts'),'// Generated by scripts/bundle-character-art.cjs; offline official artwork.\nexport const characterImages = {\n'+rows.join(',\n')+'\n} as const;\n');
})();
